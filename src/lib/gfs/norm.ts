/**
 * 엄격 품명 정규화:
 * - 앞쪽 창고 접두어([냉장], [냉장1], [냉장2], [냉동], [상온], [부자재])만 제거하고
 * - 괄호/대괄호 안의 규격·색상·상하 구분((적색)/(청색), (상)/(하), (1.8L*6EA)/(16.5kg/통), (푸른원)/(한식용) 등)은 그대로 보존!
 */
export function strictNormName(s: unknown): string {
  const raw = String(s ?? '')
    .normalize('NFC')
    .trim()
    .replace(/^\[(?:냉장1?|냉장2?|냉동|상온|부자재)\]\s*/i, '');
  return raw.replace(/[\s()[\]{}*_\-.,/]/g, '').toLowerCase();
}

